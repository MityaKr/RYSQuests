package works.repka.rysquests.integration.ftbq;

import java.nio.file.Files;
import java.nio.file.Path;
import java.util.Optional;
import net.minecraft.network.chat.Component;
import net.minecraft.server.packs.PackLocationInfo;
import net.minecraft.server.packs.PackSelectionConfig;
import net.minecraft.server.packs.PathPackResources;
import net.minecraft.server.packs.repository.BuiltInPackSource;
import net.minecraft.server.packs.repository.Pack;
import net.minecraft.server.packs.repository.PackSource;
import net.neoforged.bus.api.IEventBus;
import net.neoforged.fml.loading.FMLPaths;
import net.neoforged.neoforge.event.AddPackFindersEvent;

/** Serves the pack generated by the FTB Quests import as an always-on pack for data and for translations. */
public final class ImportedPack {
    private static final String PACK_ID = "rysquests/imported";

    private ImportedPack() {
    }

    public static Path root() {
        return FMLPaths.CONFIGDIR.get().resolve("rysquests").resolve("import");
    }

    public static void register(IEventBus modBus) {
        // The source runs on every rescan, so a pack created by an import appears on the next reload.
        modBus.addListener((AddPackFindersEvent event) -> event.addRepositorySource(consumer -> {
            Path root = root();
            if (!Files.isRegularFile(root.resolve("pack.mcmeta"))) {
                return;
            }
            Pack pack = Pack.readMetaAndCreate(
                    new PackLocationInfo(PACK_ID, Component.literal(PACK_ID), PackSource.BUILT_IN, Optional.empty()),
                    BuiltInPackSource.fromName(info -> new PathPackResources(info, root)),
                    event.getPackType(),
                    new PackSelectionConfig(true, Pack.Position.TOP, false));
            if (pack != null) {
                consumer.accept(pack);
            }
        }));
    }
}
